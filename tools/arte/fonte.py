# Acentos (2 linhas acima da letra) e letras acentuadas.
ACENTOS = {
    'agudo': ['...#.', '..#..'],
    'grave': ['.#...', '..#..'],
    'circunflexo': ['..#..', '.#.#.'],
    'til': ['.##.#', '#..#.'],
    'trema': ['.#.#.', '.....'],
}
ACENTUADAS = {
    'Á': ('A', 'agudo'), 'À': ('A', 'grave'), 'Â': ('A', 'circunflexo'), 'Ã': ('A', 'til'),
    'É': ('E', 'agudo'), 'Ê': ('E', 'circunflexo'),
    'Í': ('I', 'agudo'),
    'Ó': ('O', 'agudo'), 'Ô': ('O', 'circunflexo'), 'Õ': ('O', 'til'),
    'Ú': ('U', 'agudo'), 'Ü': ('U', 'trema'),
}

CEL_W, CEL_H = 5, 10
CORES = {
    'branca': [(252, 252, 252)],
    'amarela': [(252, 236, 120), (252, 216, 0), (248, 168, 0)],
    'vermelha': [(252, 120, 96), (232, 40, 24), (176, 16, 16)],
    'ciano': [(160, 252, 252), (60, 188, 252), (0, 136, 220)],
    'cinza': [(172, 172, 184)],
    # Gradiente "metálico" de título de fliperama: amarelo claro → laranja → vermelho.
    'metal': [(255, 252, 200), (252, 224, 64), (252, 168, 16), (240, 96, 8), (200, 48, 8)],
}


def _glifo(ch):
    """Retorna matriz 5x10 (lista de strings) do caractere."""
    if ch in ACENTUADAS:
        base, acento = ACENTUADAS[ch]
        g = _glifo(base)
        a = ACENTOS[acento]
        w = len(g[2])
        # Letras estreitas (Í) usam só o miolo do acento.
        topo = [linha if w >= 5 else linha[1:1 + w] for linha in a]
        return topo + g[2:]
    if ch == 'Ç':
        g = _glifo('C')
        return g[:9] + ['.##..']
    rows = LETRAS[ch]
    w = len(rows[0])
    vazio = '.' * w
    return [vazio, vazio] + rows + [vazio]


def caracteres():
    return ''.join(LETRAS.keys()) + ''.join(ACENTUADAS.keys()) + 'Ç'


def gerar_fonte(cor):
    chars = caracteres()
    cw, ch = CEL_W + 2, CEL_H + 2
    img = nova(cw * len(chars), ch)
    p = img.load()
    tons = CORES[cor]
    meta = []
    for i, c in enumerate(chars):
        g = _glifo(c)
        largura = max(len(l) for l in g)
        for y, linha in enumerate(g):
            for x, v in enumerate(linha):
                if v == '#':
                    # tom por linha: o gradiente acompanha a altura da letra (linhas 2–8)
                    t = min(len(tons) - 1, max(0, (y - 2) * len(tons) // 7))
                    p[i * cw + 1 + x, 1 + y] = tons[t] + (255,)
        meta.append({'esquerda': 1, 'largura': largura})
    from .base import contorno
    img = contorno(img, CONTORNO, diagonal=True)
    return img, {
        'caracteres': chars,
        'celula': [cw, ch],
        'alturaLinha': 11,
        'larguraEspaco': 3,
        'glifos': meta,
    }


def gerar_json():
    _, meta = gerar_fonte('branca')
    return json.dumps(meta, ensure_ascii=False)
